#!/usr/bin/env python3
"""Builds core/.../paint/CanTopArt.kt from the owner's photograph of a spray can top.

The source is a strip of five top-down views of a can top on a transparent background, supplied by
the owner (not fetched from anywhere). The dome is clear in places on purpose: the paint colour sits
BEHIND the picture and shows through it. The second view is cut out whole, squared, shrunk to
128 x 128 (premultiplied, so soft edges stay clean) and stored as grey level + alpha, base64, with the
radius of the can's outer rim so the colour disc behind it can be drawn to fit.

Usage: python3 tools/canart/make.py <source.png>
"""
import base64, os, sys
import numpy as np
from PIL import Image

SIZE = 128
OUT = os.path.join(os.path.dirname(__file__), "..", "..", "core", "src", "commonMain", "kotlin",
                   "com", "hereliesaz", "stencilartist", "core", "paint", "CanTopArt.kt")

src = Image.open(sys.argv[1]).convert("RGBA")
tile = src.crop((136, 434, 584, 868))                    # the second of the five views, whole
w, h = tile.size
side = max(w, h)
square = Image.new("RGBA", (side, side), (0, 0, 0, 0))
square.paste(tile, ((side - w) // 2, (side - h) // 2))
small = square.convert("RGBa").resize((SIZE, SIZE), Image.LANCZOS).convert("RGBA")   # premultiplied resize
a = np.array(small).astype(np.float64)
grey = np.rint(a[..., :3].mean(axis=2)).astype(np.uint8)
alpha = a[..., 3].astype(np.uint8)
ys, xs = np.where(alpha > 200)
radius = min(xs.max() - xs.min(), ys.max() - ys.min()) / 2 + 0.5
centre = ((xs.min() + xs.max()) / 2 + 0.5, (ys.min() + ys.max()) / 2 + 0.5)
packed = np.dstack([grey, alpha]).tobytes()
text = base64.b64encode(packed).decode()
lines = [text[i:i + 100] for i in range(0, len(text), 100)]
body = " +\n        ".join('"%s"' % l for l in lines)
with open(OUT, "w") as f:
    f.write(f'''// GENERATED by tools/canart/make.py from the owner's photograph of a can top. Do not edit.
package com.hereliesaz.stencilartist.core.paint

/** The can top picture as grey level and alpha, [SIZE] x [SIZE] pixels, two bytes each, base64. */
internal object CanTopArt {{
    const val SIZE = {SIZE}

    /** Centre and radius, in pixels, of the can's outer rim: the colour disc behind the picture. */
    const val CENTRE_X = {centre[0]:.2f}
    const val CENTRE_Y = {centre[1]:.2f}
    const val RADIUS = {radius:.2f}

    const val DATA =
        {body}
}}
''')
print("wrote", os.path.normpath(OUT), len(text), "base64 chars")
