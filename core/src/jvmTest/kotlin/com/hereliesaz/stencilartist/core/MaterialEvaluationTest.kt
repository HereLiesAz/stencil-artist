package com.hereliesaz.stencilartist.core

import java.awt.image.BufferedImage
import java.io.File
import javax.imageio.ImageIO
import kotlin.math.abs
import kotlin.math.roundToInt
import kotlin.test.Test
import kotlin.test.assertContentEquals
import kotlin.test.assertEquals
import kotlin.test.assertTrue

/**
 * Compare source skin, artist-guided compensation and solid material against an independent
 * reference. The synthetic case is a repeatable sanity check, not real-photo material recovery.
 * Optional real captures and external estimator outputs are read without resizing or guessing
 * their depth orientation. No files are sent to a service.
 */
class MaterialEvaluationTest {
    private data class Sample(
        val source: RgbaImage,
        val reference: RgbaImage,
        val depth: FloatArray,
        val assumed: OriginalLightCompensation,
        val regions: IntArray,
        val solidRgb: Int = 0xFFFFFF,
        val candidate: RgbaImage? = null,
    )

    @Test
    fun compareMaterialBaselinesOnKnownReflectance() {
        val w = 96
        val h = 64
        val regions = IntArray(w * h) { i ->
            val x = i % w
            val y = i / w
            when {
                x < 2 || x >= w - 2 || y < 2 || y >= h - 2 -> 0
                x in 10..22 && y in 12..25 -> 2 // independent cast shadow
                x in 68..82 && y in 38..50 -> 3 // independent specular highlight
                else -> 1
            }
        }
        val reference = IntArray(w * h) { i ->
            if (regions[i] == 0) 0 else if (i / w < h / 2) 0xFF804020.toInt() else 0xFF306090.toInt()
        }
        // Hand-authored exposure multipliers approximate two oppositely facing facets.
        // Neither reference nor observations are generated by the renderer under test.
        val observed = IntArray(reference.size) { i ->
            val rgb = reference[i]
            if (regions[i] == 0) 0 else {
                val factor = (if (i % w < w / 2) .5 else 1.25) *
                    (if (regions[i] == 2) .4 else 1.0)
                val specular = if (regions[i] == 3) 85 else 0
                fun channel(shift: Int) = ((rgb ushr shift and 255) * factor + specular).roundToInt().coerceIn(0, 255)
                0xFF000000.toInt() or (channel(16) shl 16) or (channel(8) shl 8) or channel(0)
            }
        }
        val depth = FloatArray(w * h) { i ->
            val x = i % w
            if (x < w / 2) x / 47f else (95 - x) / 47f
        }
        val sample = Sample(RgbaImage(w, h, observed), RgbaImage(w, h, reference), depth,
            OriginalLightCompensation(amount = 1f, azimuth = 0f, elevation = 45f), regions)
        val out = System.getenv("STENCIL_MATERIAL_OUTPUT")?.let { File(it, "controlled").apply { mkdirs() } }
        val scores = evaluate(sample, out)
        assertTrue(scores.getValue("compensated:diffuse") < scores.getValue("source:diffuse"),
            "Compensation should reduce diffuse RGB error in the known two-facet scene")
        assertTrue(scores.getValue("compensated:diffuse") < scores.getValue("solid:diffuse"))
        assertTrue(scores.getValue("compensated:cast_shadow") > scores.getValue("compensated:diffuse"),
            "Unmodeled cast shadow remains an error; this is not intrinsic decomposition")
        assertTrue(scores.getValue("compensated:specular") > scores.getValue("compensated:diffuse"),
            "Unmodeled highlight remains an error")
        assertContentEquals(observed, sample.source.pixels)
    }

    @Test
    fun evaluateOptionalRealPhotographCases() {
        val root = System.getenv("STENCIL_MATERIAL_CASES")?.let(::File) ?: return
        val cases = root.listFiles()?.filter { it.isDirectory }?.sortedBy { it.name }.orEmpty()
        require(cases.isNotEmpty()) { "STENCIL_MATERIAL_CASES contains no case directories" }
        val output = requireNotNull(System.getenv("STENCIL_MATERIAL_OUTPUT")) { "Set STENCIL_MATERIAL_OUTPUT for real-case results" }
        for (dir in cases) {
            val source = read(File(dir, "source.png"))
            val reference = read(File(dir, "reference.png"))
            val depthFile = requireNotNull(ImageIO.read(File(dir, "depth.png")))
            require(depthFile.width == source.width && depthFile.height == source.height &&
                depthFile.raster.numBands == 1 && depthFile.sampleModel.getSampleSize(0) == 16) {
                "Depth must be an aligned unsigned 16-bit grayscale PNG"
            }
            val depth = FloatArray(source.pixels.size) { p ->
                depthFile.raster.getSample(p % source.width, p / source.width, 0) / 65535f
            }
            val regionImage = requireNotNull(ImageIO.read(File(dir, "regions.png")))
            require(regionImage.width == source.width && regionImage.height == source.height &&
                regionImage.raster.numBands == 1)
            val regions = IntArray(depth.size) { p -> regionImage.raster.getSample(p % source.width, p / source.width, 0) }
            require(regions.all { it in 0..3 } && regions.any { it == 1 }) { "Region IDs must be 0, 1, 2 or 3 with a diffuse region" }
            val properties = java.util.Properties().apply { File(dir, "case.properties").inputStream().use(::load) }
            fun setting(name: String) = requireNotNull(properties.getProperty(name)) { "Missing $name in ${dir.name}" }
            val assumed = OriginalLightCompensation(amount = setting("amount").toFloat(),
                azimuth = setting("azimuth").toFloat(), elevation = setting("elevation").toFloat(),
                ambient = setting("ambient").toFloat(), depthStrength = setting("depthStrength").toFloat(),
                reverseDepth = setting("reverseDepth").toBooleanStrict())
            val candidate = File(dir, "candidate.png").takeIf { it.isFile }?.let(::read)
            evaluate(Sample(source, reference, depth, assumed, regions, setting("solidRgb").toInt(16), candidate),
                File(output, "real/${dir.name}").apply { mkdirs() })
        }
    }

    /** Absolute RGB MAE and one globally exposure-aligned RGB RMSE per region, in 8-bit levels. */
    private fun evaluate(sample: Sample, out: File?): Map<String, Double> {
        val source = sample.source
        val reference = sample.reference
        require(reference.width == source.width && reference.height == source.height)
        require(sample.solidRgb in 0..0xFFFFFF)
        require(sample.regions.size == source.pixels.size)
        val candidates = linkedMapOf("source" to source,
            "compensated" to DepthLighting.compensateOriginal(source, sample.depth, sample.assumed),
            "solid" to RgbaImage(source.width, source.height, IntArray(source.pixels.size) { i ->
                val p = source.pixels[i]
                if (p ushr 24 == 0) p else (p and 0xFF000000.toInt()) or sample.solidRgb
            }))
        sample.candidate?.let { candidates["candidate"] = it }
        val regionNames = listOf("excluded", "diffuse", "cast_shadow", "specular")
        val valid = source.pixels.indices.filter { i ->
            sample.regions[i] != 0 && source.pixels[i] ushr 24 == 255 && reference.pixels[i] ushr 24 == 255
        }
        require(valid.any { sample.regions[it] == 1 }) { "No opaque diffuse reference samples" }
        val scores = linkedMapOf<String, Double>()
        val csv = StringBuilder("method,region,pixels,mae_rgb_8bit,global_diffuse_exposure_gain,aligned_rmse_rgb_8bit\n")
        fun component(pixel: Int, channel: Int) = pixel ushr channel and 255
        for ((name, image) in candidates) {
            require(image.width == source.width && image.height == source.height)
            // Reject missing/misaligned alpha rather than rewarding an estimator for hiding errors.
            assertEquals(source.pixels.map { it ushr 24 }, image.pixels.map { it ushr 24 })
            var cross = 0.0
            var norm = 0.0
            for (i in valid) if (sample.regions[i] == 1) for (shift in listOf(16, 8, 0)) {
                val v = component(image.pixels[i], shift).toDouble()
                cross += v * component(reference.pixels[i], shift)
                norm += v * v
            }
            val gain = if (norm > 0.0) cross / norm else 1.0
            for (region in 1..3) {
                val points = valid.filter { sample.regions[it] == region }
                if (points.isEmpty()) continue
                var absolute = 0.0
                var squared = 0.0
                for (i in points) for (shift in listOf(16, 8, 0)) {
                    val observed = component(image.pixels[i], shift)
                    val expected = component(reference.pixels[i], shift)
                    absolute += abs(observed - expected)
                    val aligned = observed * gain - expected
                    squared += aligned * aligned
                }
                val count = points.size * 3.0
                val mae = absolute / count
                scores["$name:${regionNames[region]}"] = mae
                csv.append(listOf(name, regionNames[region], points.size, mae, gain,
                    kotlin.math.sqrt(squared / count)).joinToString(",")).append('\n')
            }
            out?.let { write(File(it, "$name.png"), image) }
        }
        out?.let {
            write(File(it, "reference.png"), reference)
            File(it, "scores.csv").writeText(csv.toString())
        }
        return scores
    }

    private fun read(file: File): RgbaImage {
        val image = requireNotNull(ImageIO.read(file)) { "Cannot read $file" }
        return RgbaImage(image.width, image.height, image.getRGB(0, 0, image.width, image.height, null, 0, image.width))
    }

    private fun write(file: File, image: RgbaImage) {
        val bitmap = BufferedImage(image.width, image.height, BufferedImage.TYPE_INT_ARGB)
        bitmap.setRGB(0, 0, image.width, image.height, image.pixels, 0, image.width)
        check(ImageIO.write(bitmap, "png", file))
    }
}
